# === Function to verify voltage trend ===
def check_voltage_trend(current_voltage, previous_voltage, current_power, previous_power, threshold=0.001):
    """
    Check the voltage vs. power trend.
    
    Returns:
        tuple: (is_anomaly, anomaly_type, message)
    """
    if previous_voltage is None or previous_power is None:
        return False, None, ""
    
    power_diff = current_power - previous_power
    voltage_diff = current_voltage - previous_voltage
    
    # Expected behavior: as power increases, voltage should decrease
    if power_diff > 0:
        # If the tension increases when it should decrease
        if voltage_diff > threshold:
            return True, "increasing", f"Voltage increased by {voltage_diff:.6f} p.u. with the increase in power"
        # If the tension remains constant
        elif abs(voltage_diff) < threshold:
            return True, "flat", f"Constant voltage with increased power"
    
    return False, None, ""

