# === Function to extract the number from the bus name ===
def extract_bus_number(bus_name):
    """Extract the number from the bus name (ej: 'Bus 4' → '4', '4' → '4')"""
    # Search for digits in the name
    numbers = re.findall(r'\d+', bus_name)
    if numbers:
        return numbers[0]  # Return the first number found
    return bus_name  # If there are no numbers, return the original name

# === Function to determine the evaluation node for a generator ===
def get_evaluation_bus_for_generator(generator):
    """
    Determine the appropriate node to evaluate the generator impedance.
    
    """
    try:
        # Obtain the generator's direct connection bus
        gen_bus = generator.bus1.cterm if hasattr(generator, 'bus1') and generator.bus1.cterm else None
        
        if not gen_bus:
            app.PrintWarn(f"No bus could be obtained for {generator.loc_name}")
            return None
        
        # Search for transformers connected to this bus
        transformers = app.GetCalcRelevantObjects("*.ElmTr2") or []
        transformers.extend(app.GetCalcRelevantObjects("*.ElmTrf") or [])
        
        for trafo in transformers:
            # Verify whether the transformer is connected to the generator bus
            if (hasattr(trafo, 'bushv') and hasattr(trafo, 'buslv')):
                # Case 1: Generator on the LV side, transformer connected to the grid on the HV side
                if trafo.buslv.cterm == gen_bus:
                    # Verify whether the transformer name follows the expected pattern
                    trafo_name = trafo.loc_name.lower()
                    gen_name = generator.loc_name.lower()
                    
                    # Search for name matches (example: "TR PV1" y "PV1")
                    if ('tr' in trafo_name and any(word in trafo_name for word in ['pv', 'wind', 'gen']) and
                        any(word in gen_name for word in ['pv', 'wind', 'gen'])):
                        app.PrintInfo(f"Generator {generator.loc_name} connected via a transformer {trafo.loc_name} (LV→HV)")
                        return trafo.bushv.cterm.loc_name
                
                # Case 2: Generator on the HV side (less common direct connection)
                elif trafo.bushv.cterm == gen_bus:
                    app.PrintInfo(f"Generator {generator.loc_name} connected to the HV side of the transformer {trafo.loc_name}")
                    return gen_bus.loc_name
        
        # If no transformer is found or it does not meet the standard, use a direct connection
        app.PrintInfo(f"Generator {generator.loc_name} connected directly to the bus {gen_bus.loc_name}")
        return gen_bus.loc_name
        
    except Exception as e:
        app.PrintWarn(f"Error determining evaluation bus for {generator.loc_name}: {str(e)}")
        # Fallback: use the generator's direct bus
        if hasattr(generator, 'bus1') and generator.bus1.cterm:
            return generator.bus1.cterm.loc_name
        return None

