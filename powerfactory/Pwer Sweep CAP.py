def test_allocation_simple(p1_kw, p2_kw, g1, g2, min_pu=0.9):
    """
    Simplified function to test a power allocation.
    Returns feasibility, the minimum voltage, and the critical bus.
    """
    # Save original values
    p1_orig = g1.pgini
    p2_orig = g2.pgini
    
    # Assign new active power values
    g1.pgini = p1_kw
    g2.pgini = p2_kw
    
    # Run load flow
    err = ldf.Execute()
    converged = (err == 0)
    
    # Obtain minimum tension
    u_min = None
    bus_critico = None
    
    if converged:
        buses = app.GetCalcRelevantObjects("*.ElmTerm") or []
        for b in buses:
            try:
                u = b.GetAttribute("m:u")
                if u is not None:
                    if u_min is None or u < u_min:
                        u_min = u
                        bus_critico = b.loc_name
            except Exception:
                continue
    
    # Restore original values
    g1.pgini = p1_orig
    g2.pgini = p2_orig
    
    # Verify feasibility
    if not converged or u_min is None:
        return False, None, None
    
    feasible = u_min >= min_pu
    return feasible, u_min, bus_critico

